/**
 * Build-time generation of the counts the marketing site prints at the visitor.
 * Runs BEFORE `next build` (see the site's `build` script), beside `gen-og.mjs`,
 * and emits `src/lib/counts.ts`.
 *
 * Why this exists: these three numbers used to be hand-typed string literals in
 * `landing/sections.tsx`, under a comment reading "Counts. Real, and checked
 * against the repo rather than remembered." Nothing checked them. The repo grew
 * and all three went stale — the front page claimed 113 components in one band
 * and 116 in the next, twelve lines apart in the same file, because one was typed
 * and the other was derived.
 *
 * So: no count a visitor can read is typed by a person. Each one below comes from
 * the same source the rest of the codebase already treats as authoritative, and
 * `--check` runs in `pnpm verify` so a drifted number fails CI instead of sitting
 * on the front page being wrong at everybody.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { DEMO_META } from "@wizeworks/silicaui-demos/meta";

const here = dirname(fileURLToPath(import.meta.url));
const REPO = join(here, "..", "..", "..");
const OUT = join(here, "..", "src", "lib", "counts.ts");

// ── components ────────────────────────────────────────────────────────────────
// The same array the docs sidebar, the sitemap, the OG images and the component
// list on the front page all read. One demo = one doc page = one component.
const components = DEMO_META.length;

// ── behaviors ─────────────────────────────────────────────────────────────────
// `HANDLERS` is the closed dispatch table in silicaui-behaviors — one handler per
// `BehaviorType`. It is parsed rather than imported because that package is a
// browser runtime and this script runs in Node at build time; the table is a flat
// object literal, so parsing it is exact rather than approximate.
//
// Note it is the REGISTERED behaviors that count, not the files in `behaviors/`:
// `scroll-strip-core.ts` is shared internals with no handler of its own, so a
// file count would say 35 for the wrong reason and then be wrong the day another
// internal module is added.
const registrySrc = readFileSync(
  join(REPO, "packages", "silicaui-behaviors", "src", "registry.ts"),
  "utf8",
);
const tableStart = registrySrc.indexOf("HANDLERS: Record<BehaviorType, BehaviorHandler> = {");
if (tableStart === -1) {
  throw new Error("gen-counts: could not find the HANDLERS table in registry.ts");
}
const table = registrySrc.slice(tableStart);
const tableBody = table.slice(table.indexOf("{") + 1, table.indexOf("};"));
const behaviorKeys = tableBody
  .split("\n")
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith("//") && !l.startsWith("/*") && !l.startsWith("*"))
  .map((l) => l.replace(/[:,].*$/, "").replace(/"/g, "").trim())
  .filter(Boolean);
const behaviors = behaviorKeys.length;
if (behaviors < 10) {
  throw new Error(`gen-counts: parsed only ${behaviors} behaviors — the parse is wrong`);
}

// ── packages ──────────────────────────────────────────────────────────────────
// PUBLISHED packages, which is what the label on screen says. `silicaui-demos` is
// `"private": true` and never reaches npm, so counting directories would print a
// number no visitor could ever install.
const pkgDir = join(REPO, "packages");
const packageNames = readdirSync(pkgDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => join(pkgDir, e.name, "package.json"))
  .filter((p) => existsSync(p))
  .map((p) => JSON.parse(readFileSync(p, "utf8")))
  .filter((p) => p.private !== true)
  .map((p) => p.name)
  .sort();
const packages = packageNames.length;
if (packages < 5) {
  throw new Error(`gen-counts: found only ${packages} published packages — the scan is wrong`);
}

// ── emit ──────────────────────────────────────────────────────────────────────
const banner = `// GENERATED by apps/site/scripts/gen-counts.mjs — do not edit.
//
// Every number the marketing site shows a visitor lives here and is derived from
// the repo, because the hand-typed versions went stale and contradicted each other
// on the front page. Run \`node apps/site/scripts/gen-counts.mjs\` to regenerate;
// \`pnpm verify\` fails if this file and the repo disagree.
`;

const body = `${banner}
/** Documented component pages — one per entry in \`DEMO_META\`. */
export const COMPONENT_COUNT = ${components};

/** Registered vanilla behaviors — the \`HANDLERS\` table in silicaui-behaviors. */
export const BEHAVIOR_COUNT = ${behaviors};

/** Published packages — \`packages/*\` excluding anything marked private. */
export const PACKAGE_COUNT = ${packages};

/** The published package names, in case a page wants to list rather than count. */
export const PACKAGE_NAMES = [
${packageNames.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
] as const;
`;

const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";

// Compare with line endings normalized. `core.autocrlf=true` rewrites this file to
// CRLF on checkout while the generator writes LF, so a byte-exact `!==` reports a
// perfectly current file as stale — on every Windows clone, with a message naming
// numbers that are correct. `gen-canvas-safelist.mjs` already normalizes; this is the
// same guard, and .gitattributes records the same hazard for the golden fixture.
const eol = (t) => t.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  if (eol(current) !== eol(body)) {
    console.error(
      "gen-counts: apps/site/src/lib/counts.ts is stale.\n" +
        `  components ${components} · behaviors ${behaviors} · packages ${packages}\n` +
        "Run: node apps/site/scripts/gen-counts.mjs",
    );
    process.exit(1);
  }
  console.log(
    `gen-counts: ok — ${components} components, ${behaviors} behaviors, ${packages} packages.`,
  );
  process.exit(0);
}

writeFileSync(OUT, body);
console.log(
  `gen-counts: wrote ${components} components, ${behaviors} behaviors, ${packages} packages.`,
);
